"""Build docs/data_inventory.md from the local raw copy of the dataset (data/raw/).

For every table it reports: files, size, format, partitioning, partition date range, missing days,
header variants across files (schema evolution) and row counts compared to the organizer's figures.

Usage: python etl/inventory.py [--no-rows]   (--no-rows skips the DuckDB row counts, which read every file)
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = REPO_ROOT / "data" / "raw"
OUT_FILE = REPO_ROOT / "docs" / "data_inventory.md"

# Row counts published by the organizer (LATAM_Bank_Dataset_Summary, v1.0.0).
EXPECTED_ROWS = {
    "customers": 150_000, "products": 400_000, "branches": 350, "service_agents": 1_200,
    "marketing_campaigns": 200, "transactions": 5_000_000, "call_center_interactions": 800_000,
    "call_transcripts": 200_000, "satisfaction_surveys": 250_000, "digital_events": 10_000_000,
    "complaints": 80_000, "campaign_sends": 2_000_000, "daily_exchange_rates": 3_000,
}
TABLE_KIND = {
    "customers": "dimension", "products": "dimension", "branches": "dimension",
    "service_agents": "dimension", "marketing_campaigns": "dimension",
    "daily_exchange_rates": "reference",
}
PARTITION_RE = re.compile(r"year=(\d{4})/month=(\d{2})/day=(\d{2})")


def read_header(path: Path) -> str:
    with path.open("r", encoding="utf-8", errors="replace", newline="") as fh:
        return fh.readline().strip().lstrip("﻿")


def collect() -> dict[str, list[Path]]:
    tables: dict[str, list[Path]] = defaultdict(list)
    for path in sorted(RAW_DIR.rglob("*.csv")):
        rel = path.relative_to(RAW_DIR)
        name = rel.parts[0] if len(rel.parts) > 1 else rel.stem
        tables[name].append(path)
    return tables


def partition_dates(files: list[Path]) -> list[dt.date]:
    dates = []
    for path in files:
        match = PARTITION_RE.search(path.as_posix())
        if match:
            dates.append(dt.date(*map(int, match.groups())))
    return sorted(dates)


def schema_variants(files: list[Path]) -> list[dict]:
    """Group consecutive files by header so schema changes show up as date ranges."""
    variants: dict[str, dict] = {}
    for path in files:
        header = read_header(path)
        match = PARTITION_RE.search(path.as_posix())
        label = "-".join(match.groups()) if match else path.name
        entry = variants.setdefault(header, {"columns": header.split(","), "files": 0,
                                             "first": label, "last": label})
        entry["files"] += 1
        entry["last"] = label
    return list(variants.values())


def count_rows(files: list[Path]) -> int:
    import duckdb  # imported lazily so --no-rows works without duckdb installed

    paths = [p.as_posix() for p in files]
    query = "SELECT count(*) FROM read_csv(?, all_varchar = true, union_by_name = true, header = true)"
    return duckdb.connect().execute(query, [paths]).fetchone()[0]


def human_size(num_bytes: int) -> str:
    size = float(num_bytes)
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024 or unit == "GB":
            return f"{size:,.1f} {unit}"
        size /= 1024
    return f"{size:,.1f} GB"


def render(tables: dict[str, list[Path]], with_rows: bool) -> str:
    today = dt.date.today().isoformat()
    lines = [
        "# Data Inventory",
        "",
        f"Generated by `etl/inventory.py` on {today} from the local raw copy (`data/raw/`), "
        "synced from the organizer's read-only S3 bucket (`s3://<bucket>/data/`, region `us-east-2`).",
        "",
        "- Origin: organizer-provided **synthetic** dataset (Factored Datathon 2026, v1.0.0). No real customer data.",
        "- Format: **CSV with a header row** for every table (no Parquet in the source).",
        "- Fact tables are Hive-partitioned as `<table>/year=YYYY/month=MM/day=DD/<table>_YYYYMMDD.csv` "
        "(one file per day); dimension and reference tables are single files at the bucket root.",
        "- Regenerate with `make inventory` (or `python etl/inventory.py`).",
        "",
        "## Summary",
        "",
        "| Table | Kind | Files | Size | Partition range | Missing days | Schema variants | Rows | Expected rows | Rows / expected |",
        "|---|---|---:|---:|---|---:|---:|---:|---:|---:|",
    ]
    details = []
    flags = []
    total_bytes = 0
    for name in sorted(tables, key=lambda t: (TABLE_KIND.get(t, "fact"), t)):
        files = tables[name]
        size = sum(p.stat().st_size for p in files)
        total_bytes += size
        dates = partition_dates(files)
        if dates:
            span = (dates[-1] - dates[0]).days + 1
            missing = span - len(set(dates))
            date_range = f"{dates[0]} → {dates[-1]}"
        else:
            missing, date_range = 0, "—"
        variants = schema_variants(files)
        row_count = count_rows(files) if with_rows else None
        rows = f"{row_count:,}" if row_count is not None else "—"
        expected = f"{EXPECTED_ROWS[name]:,}" if name in EXPECTED_ROWS else "—"
        ratio = "—"
        if row_count is not None and name in EXPECTED_ROWS:
            r = row_count / EXPECTED_ROWS[name]
            ratio = f"{r:.1%}"
            if abs(r - 1) > 0.05:
                flags.append(f"- `{name}`: {row_count:,} rows vs {EXPECTED_ROWS[name]:,} published ({r:.1%}).")
        if missing:
            flags.append(f"- `{name}`: {missing} day partition(s) missing inside {date_range}.")
        if len(variants) > 1:
            flags.append(f"- `{name}`: {len(variants)} header variants (schema evolution), see details below.")
        kind = TABLE_KIND.get(name, "fact")
        lines.append(f"| `{name}` | {kind} | {len(files):,} | {human_size(size)} | {date_range} | "
                     f"{missing} | {len(variants)} | {rows} | {expected} | {ratio} |")

        details += [f"### `{name}`", ""]
        for i, v in enumerate(variants, 1):
            span = v["first"] if v["first"] == v["last"] else f"{v['first']} → {v['last']}"
            details.append(f"- Variant {i}: {len(v['columns'])} columns, {v['files']} file(s), {span}")
            details.append(f"  - `{', '.join(v['columns'])}`")
        details.append("")

    lines += ["", f"Total on disk: **{human_size(total_bytes)}**.", "",
              "Row counts are raw physical rows (before dedup); the organizer states ~2% intentional "
              "duplicates, ~5% nulls in nullable fields, late arrivals and schema evolution.", "",
              "## Automatic flags", "",
              *(flags or ["- None."]), "",
              "Deviations from the published row counts must be explained during profiling "
              "(e.g. records still to arrive late, or published figures being approximate). "
              "Re-run `make data` periodically: `aws s3 sync` only fetches new or changed objects.", "",
              "## Columns and schema variants per table", "", *details]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--no-rows", action="store_true", help="Skip row counts.")
    args = parser.parse_args()
    if not RAW_DIR.exists():
        raise SystemExit("data/raw/ not found. Run `make data` first.")
    tables = collect()
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(render(tables, with_rows=not args.no_rows), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT_FILE.relative_to(REPO_ROOT)} ({len(tables)} tables)")


if __name__ == "__main__":
    main()
